# ═══════════════════════════════════════════════════════════════

async def main() -> None:
    """Запуск бота в режиме polling."""
    await dp.start_polling(bot)


if __name__ == "__main__":
    try:
        asyncio.run(main())
    except KeyboardInterrupt:
        print("Бот остановлен")
